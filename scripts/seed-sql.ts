// Writes the placeholder content as SQL inserts (supabase/seed/content.sql), so the admin
// starts with the same content the static preview showed. Run: npx tsx scripts/seed-sql.ts
import { writeFileSync, mkdirSync } from "node:fs";
import { about, albums } from "../src/content/pages";
import { articles, bank, hero, impact, programmes, site } from "../src/content/site";

const q = (v: unknown) =>
  v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`;
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (v: string[]) => `array[${v.map(q).join(", ")}]::text[]`;

const out: string[] = ["-- Generated by scripts/seed-sql.ts. Placeholder content.", "begin;"];

out.push(`update public.site_settings set
  email = ${q(site.email)}, phone = ${q(site.phone)}, whatsapp = ${q(site.whatsapp)}, address = ${q(site.address)},
  notify_email = 'molayokunmi@gmail.com',
  socials = ${j(site.socials)},
  bank_accounts = ${j(bank.accounts)},
  impact = ${j(impact.stats)},
  hero = ${j({ title: hero.title, lead: hero.lead, slides: hero.slides })}
where id;`);

programmes.forEach((p, i) => {
  out.push(`insert into public.programmes (slug, title, summary, intro, image, covers, steps, stat, photos, sort)
values (${q(p.slug)}, ${q(p.title)}, ${q(p.summary)}, ${q(p.intro)}, ${j(p.image)}, ${arr(p.covers)}, ${j(p.steps)}, ${j(p.stat)}, ${j(p.photos)}, ${i});`);
});

const day = 86_400_000;
articles.forEach((a, i) => {
  const date = new Date(Date.UTC(2026, 9, 20) - i * 19 * day).toISOString();
  out.push(`insert into public.articles (slug, title, excerpt, body, image, photos, programme, published, published_at)
values (${q(a.slug)}, ${q(a.title)}, ${q(a.excerpt)}, ${q(a.body.join("\n\n"))}, ${j(a.image)}, ${j(a.photos ?? [])}, ${q(a.programme)}, true, ${q(date)});`);
});

albums.forEach((al, i) => {
  out.push(`with al as (insert into public.albums (slug, title, sort) values (${q(al.slug)}, ${q(al.title)}, ${i}) returning id)
insert into public.photos (album_id, image, caption, sort) select al.id, v.image, v.caption, v.sort from al, (values
${al.photos.map((p, k) => `  (${j(p.image)}, ${q(p.caption)}, ${k})`).join(",\n")}
) v(image, caption, sort);`);
});

about.people.forEach((p, i) => {
  out.push(`insert into public.people (name, role, sort) values (${q(p.name)}, ${q(p.role)}, ${i});`);
});

out.push("commit;");
mkdirSync("supabase/seed", { recursive: true });
writeFileSync("supabase/seed/content.sql", out.join("\n\n") + "\n");
console.log("wrote supabase/seed/content.sql");
